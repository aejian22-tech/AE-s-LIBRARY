/* ==========================================================================
   Application State & DOM Elements
   ========================================================================== */
let currentStory = null;
let currentChapterIndex = 0;
let fontSize = 1.05;

const bookshelf = document.getElementById('bookshelf');
const searchInput = document.getElementById('searchInput');
const genreSelect = document.getElementById('genreSelect');
const storyCount = document.getElementById('storyCount');

// Modal Elements
const modal = document.getElementById('readerModal');
const closeModalBtn = document.getElementById('closeModalBtn');
const modalTitle = document.getElementById('modalTitle');
const modalAuthor = document.getElementById('modalAuthor');
const modalGenre = document.getElementById('modalGenre');
const modalSynopsis = document.getElementById('modalSynopsis');
const modalSpine = document.getElementById('modalSpine');
const readerBody = document.getElementById('readerBody');
const storyContent = document.getElementById('storyContent');
const chapterTitle = document.getElementById('chapterTitle');

/* ==========================================================================
   Render Bookshelf Grid
   ========================================================================== */
function renderBookshelf(stories) {
  bookshelf.innerHTML = '';
  storyCount.textContent = `${stories.length} Books Available`;

  stories.forEach(story => {
    const card = document.createElement('div');
    card.className = 'book-card';
    card.onclick = () => openReader(story);

    card.innerHTML = `
      <div class="book-3d" style="background: ${story.color}">
        <span class="book-tag">${story.genre}</span>
        <div>
          <h3 class="book-title">${story.title}</h3>
          <p class="book-author">By ${story.author}</p>
        </div>
      </div>
    `;
    bookshelf.appendChild(card);
  });
}

/* ==========================================================================
   Filtering & Search Functions
   ========================================================================== */
function filterStories() {
  const query = searchInput.value.toLowerCase();
  const selectedGenre = genreSelect.value;

  const filtered = blStories.filter(story => {
    const matchesSearch = story.title.toLowerCase().includes(query) ||
                          story.author.toLowerCase().includes(query) ||
                          story.genre.toLowerCase().includes(query);
    const matchesGenre = selectedGenre === 'all' || story.genre === selectedGenre;
    return matchesSearch && matchesGenre;
  });

  renderBookshelf(filtered);
}

searchInput.addEventListener('input', filterStories);
genreSelect.addEventListener('change', filterStories);

/* ==========================================================================
   Reader Modal Logic
   ========================================================================== */
function openReader(story) {
  currentStory = story;
  currentChapterIndex = 0;

  modalTitle.textContent = story.title;
  modalAuthor.textContent = story.author;
  modalGenre.textContent = story.genre;
  modalSynopsis.textContent = story.synopsis;
  modalSpine.style.background = story.color;

  updateChapter();
  modal.classList.remove('hidden');
}

function updateChapter() {
  chapterTitle.textContent = `Chapter ${currentChapterIndex + 1} of ${currentStory.chapters.length}`;
  storyContent.innerHTML = `<p>${currentStory.chapters[currentChapterIndex]}</p>`;
}

// Close Modal
closeModalBtn.addEventListener('click', () => {
  modal.classList.add('hidden');
});

// Chapter Navigation
document.getElementById('prevChapter').addEventListener('click', () => {
  if (currentChapterIndex > 0) {
    currentChapterIndex--;
    updateChapter();
  }
});

document.getElementById('nextChapter').addEventListener('click', () => {
  if (currentChapterIndex < currentStory.chapters.length - 1) {
    currentChapterIndex++;
    updateChapter();
  }
});

/* Font Controls */
document.getElementById('incFont').addEventListener('click', () => {
  fontSize += 0.1;
  readerBody.style.fontSize = `${fontSize}rem`;
});

document.getElementById('decFont').addEventListener('click', () => {
  if (fontSize > 0.8) {
    fontSize -= 0.1;
    readerBody.style.fontSize = `${fontSize}rem`;
  }
});

/* Theme Customization */
document.querySelectorAll('.theme-btn').forEach(btn => {
  btn.addEventListener('click', (e) => {
    const theme = e.target.getAttribute('data-theme');
    readerBody.className = `reader-body theme-${theme}`;
  });
});

// Initial Render
renderBookshelf(blStories);